/* Check memory, fetched values, source/R0 preservation and signed offsets. */
#define ATOMIC_CASE(SIZE, OP, OFF, INITIAL_R0, MEMORY, SOURCE, RETURN_R0) \
{ \
	.descr = #SIZE " " #OP " offset=" #OFF " r0=" #INITIAL_R0, \
	.insns = { \
		BPF_MOV64_IMM(BPF_REG_0, INITIAL_R0), \
		BPF_ST_MEM(BPF_DW, BPF_REG_10, -16, 15), \
		BPF_MOV64_IMM(BPF_REG_1, 3), \
		BPF_MOV64_REG(BPF_REG_2, BPF_REG_10), \
		BPF_ALU64_IMM(BPF_ADD, BPF_REG_2, -16 - (OFF)), \
		BPF_ATOMIC_OP(SIZE, OP, BPF_REG_2, BPF_REG_1, OFF), \
		BPF_LDX_MEM(SIZE, BPF_REG_2, BPF_REG_10, -16), \
		BPF_JMP_IMM(BPF_JNE, BPF_REG_2, MEMORY, 4), \
		BPF_JMP_IMM(BPF_JNE, BPF_REG_1, SOURCE, 3), \
		BPF_JMP_IMM(BPF_JNE, BPF_REG_0, RETURN_R0, 2), \
		BPF_MOV64_IMM(BPF_REG_0, 0), \
		BPF_EXIT_INSN(), \
		BPF_MOV64_IMM(BPF_REG_0, 1), \
		BPF_EXIT_INSN(), \
	}, \
	.retval = 0, \
}

